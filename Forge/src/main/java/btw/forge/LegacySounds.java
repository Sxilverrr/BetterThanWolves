package btw.forge;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.sounds.SoundEvent;
import net.minecraftforge.eventbus.api.IEventBus;
import net.minecraftforge.registries.DeferredRegister;
import net.minecraftforge.registries.ForgeRegistries;
import net.minecraftforge.registries.RegistryObject;
import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.Collections;
import java.util.HashMap;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.concurrent.ConcurrentHashMap;

/**
 * The one resolver from a 1.5.2 sound name ("random.click", "mob.cow.say4", "step.grass", ...) to a
 * 1.20.1 {@link SoundEvent}. FC and frozen 1.5.2 sound calls are meant to resolve here only
 * (WorldBridge, {@link SoundMapping}, block sound types, client-side sound sinks).
 *
 * <p>1.5.2 played sounds by pool name. SoundPool.addSound filed every sound3/&lt;path&gt;N.ogg under
 * &lt;path&gt; with '/' -> '.' and the trailing digits removed, and BTW's FCMOD there also filed a
 * numbered file under its own numbered name, so "mob.cow.say4" meant exactly say4.ogg
 * (vanilla/client SoundPool.java:46-97; sound3 routing Minecraft.java:2098-2106). Each such name is
 * one {@code betterthanwolves:<name>} event in assets/betterthanwolves/sounds.json that plays that
 * 1.5.2 pool from the 1.20.1 vanilla assets: the file at the same path, or the byte-identical file
 * Mojang later renamed (mob/zombiepig -> mob/zombified_piglin, "affectionate scream" ->
 * affectionate_scream, ...). sounds.json is generated by the Forge Gradle task
 * generateLegacySoundsJson, which documents those rules and how each event's subtitle is picked.
 * Every event plays 1.5.2 files only: a name 1.5.2 had no file for has no event and stays silent.</p>
 *
 * <p>One variable-range SoundEvent is registered per sounds.json key: range 16 * max(1, volume)
 * blocks, as 1.5.2 WorldManager.playSound. Lookups go through {@link #toKey}. An unknown name
 * resolves to null and is logged once; no minecraft:* event is ever guessed from a 1.5.2 name.</p>
 */
public final class LegacySounds {

    private static final Logger LOGGER = LogManager.getLogger("BTW-LegacySounds");

    private static final String SOUNDS_JSON = "/assets/" + BTWForgeMod.MOD_ID + "/sounds.json";

    /**
     * Names 1.5.2 played without any sound file existing, so SoundPool found nothing and 1.5.2 was
     * silent: they resolve to null (silent here too) and are logged at debug, not as unknown.
     */
    private static final Set<String> SILENT_IN_1_5_2 = Set.of(
            "mob.attack",                // vanilla/client EntitySlime.java:247; no sound3/mob/attack*.ogg
            "step.anvil",                // StepSoundAnvil keeps the base getStepSound(); no sound3/step/anvil*.ogg
            "damage.thorns",             // vanilla/client EnchantmentThorns.java:74; no sound3/damage/thorns*.ogg
            "mob.villager.default",      // vanilla/client EntityVillager.java:274-290; the 1.5.2 asset
            "mob.villager.defaulthurt",  //   index has no villager sound file at all
            "mob.villager.defaultdeath",
            "mob.witch.idle",            // vanilla/client EntityWitch.java:58-74; nor any witch sound file
            "mob.witch.hurt",
            "mob.witch.death");

    private static final int MAX_LOGGED_NAMES = 256;
    private static final Set<String> LOGGED = ConcurrentHashMap.newKeySet();

    public static final DeferredRegister<SoundEvent> SOUND_EVENTS =
            DeferredRegister.create(ForgeRegistries.SOUND_EVENTS, BTWForgeMod.MOD_ID);

    /** sounds.json key -> registry entry. Built once by the class initialiser, read-only afterwards. */
    private static final Map<String, RegistryObject<SoundEvent>> EVENTS = createEvents();

    private LegacySounds() {}

    /** Hooks the legacy sound events into the mod event bus. Called once, from the mod constructor. */
    public static void register(IEventBus modEventBus) {
        SOUND_EVENTS.register(modEventBus);
        LOGGER.info("Registering {} legacy (1.5.2) sound events from {}", EVENTS.size(), SOUNDS_JSON);
    }

    /**
     * The SoundEvent that plays the 1.5.2 sound {@code legacyName}, or null when 1.5.2 had no such
     * sound (or the sound registry is not populated yet). A namespaced id ("minecraft:block.mud.step")
     * is already a 1.20.1 event, handed to FC on purpose (ModernBlockStandIn reports a post-1.5.2
     * block's live SoundType that way); it resolves through the sound registry. 1.5.2 names never
     * contain ':'. Never throws; safe from any thread.
     */
    public static SoundEvent resolve(String legacyName) {
        if (legacyName == null || legacyName.isEmpty()) return null;
        try {
            if (legacyName.indexOf(':') > 0) {
                ResourceLocation id = ResourceLocation.tryParse(legacyName);
                SoundEvent modern = id != null ? BuiltInRegistries.SOUND_EVENT.get(id) : null;
                if (modern != null) return modern;
            } else {
                RegistryObject<SoundEvent> entry = EVENTS.get(toKey(legacyName));
                if (entry != null) {
                    return entry.isPresent() ? entry.get() : null;
                }
            }
            if (LOGGED.size() < MAX_LOGGED_NAMES && LOGGED.add(legacyName)) {
                if (SILENT_IN_1_5_2.contains(legacyName)) {
                    LOGGER.debug("1.5.2 sound '{}' had no sound file in 1.5.2 either; not played", legacyName);
                } else {
                    LOGGER.warn("Unknown sound '{}': no such 1.5.2 sound or 1.20.1 sound event, not played",
                            legacyName);
                }
            }
        } catch (Throwable t) {
            if (LOGGED.size() < MAX_LOGGED_NAMES && LOGGED.add(legacyName)) {
                LOGGER.warn("Could not resolve 1.5.2 sound '{}': {}", legacyName, t.toString());
            }
        }
        return null;
    }

    /** True when {@code legacyName} has a registered legacy sound event. */
    public static boolean isKnown(String legacyName) {
        if (legacyName == null || legacyName.isEmpty()) return false;
        RegistryObject<SoundEvent> entry = EVENTS.get(toKey(legacyName));
        return entry != null && entry.isPresent();
    }

    /** True when 1.5.2 itself played nothing for {@code legacyName} (no sound file existed). */
    public static boolean isSilentIn152(String legacyName) {
        return legacyName != null && SILENT_IN_1_5_2.contains(legacyName);
    }

    /** Number of legacy sound events (sounds.json keys) registered. */
    public static int eventCount() {
        return EVENTS.size();
    }

    /**
     * The sounds.json key of a 1.5.2 name. Resource paths are lower case without spaces, so
     * "fireworks.largeBlast" -> "fireworks.largeblast" and "random.wood click" -> "random.wood_click".
     * Must match the key rule in Forge/build.gradle generateLegacySoundsJson.
     */
    static String toKey(String legacyName) {
        return legacyName.toLowerCase(Locale.ROOT).replace(' ', '_');
    }

    private static Map<String, RegistryObject<SoundEvent>> createEvents() {
        Map<String, RegistryObject<SoundEvent>> events = new HashMap<>();
        for (String key : readEventKeys()) {
            try {
                ResourceLocation id = new ResourceLocation(BTWForgeMod.MOD_ID, key);
                events.put(key, SOUND_EVENTS.register(key, () -> SoundEvent.createVariableRangeEvent(id)));
            } catch (IllegalStateException e) {
                // DeferredRegister is sealed once RegisterEvent has fired; nothing else can be added.
                LOGGER.error("Legacy sound events registered too late ({}); the remaining ones are missing",
                        e.getMessage());
                break;
            } catch (Throwable t) {
                LOGGER.warn("Skipping legacy sound event '{}': {}", key, t.toString());
            }
        }
        return Collections.unmodifiableMap(events);
    }

    private static Set<String> readEventKeys() {
        Set<String> keys = new TreeSet<>();
        try (InputStream in = openSoundsJson()) {
            if (in == null) {
                LOGGER.error("{} is missing from the mod jar: every 1.5.2 sound will be silent", SOUNDS_JSON);
                return keys;
            }
            try (Reader reader = new InputStreamReader(in, StandardCharsets.UTF_8)) {
                JsonObject root = JsonParser.parseReader(reader).getAsJsonObject();
                for (String key : root.keySet()) {
                    if (ResourceLocation.isValidPath(key)) {
                        keys.add(key);
                    } else {
                        LOGGER.warn("Ignoring {} key '{}': not a valid resource path", SOUNDS_JSON, key);
                    }
                }
            }
        } catch (Throwable t) {
            LOGGER.error("Could not read {}: every 1.5.2 sound will be silent", SOUNDS_JSON, t);
            keys.clear();
        }
        return keys;
    }

    private static InputStream openSoundsJson() {
        InputStream in = LegacySounds.class.getResourceAsStream(SOUNDS_JSON);
        if (in == null) {
            ClassLoader loader = LegacySounds.class.getClassLoader();
            if (loader != null) in = loader.getResourceAsStream(SOUNDS_JSON.substring(1));
        }
        return in;
    }
}
